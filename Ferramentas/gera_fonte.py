def desenha(partes):
    """partes: lista de (linhas, linha_topo). linha_topo 0 = topo da letra, -2 = acento, 7 = abaixo da base."""
    pen = TTGlyphPen(None)
    for linhas, topo in partes:
        for i, linha in enumerate(linhas):
            y0 = (6 - (topo + i)) * PX   # linha 6 encosta na base
            x = 0
            while x < len(linha):
                if linha[x] != "#":
                    x += 1
                    continue
                x0 = x
                while x < len(linha) and linha[x] == "#":
                    x += 1
                # sentido horario (contorno externo TrueType)
                pen.moveTo((x0 * PX, y0))
                pen.lineTo((x0 * PX, y0 + PX))
                pen.lineTo((x * PX, y0 + PX))
                pen.lineTo((x * PX, y0))
                pen.closePath()
    return pen.glyph()


glifos = {".notdef": TTGlyphPen(None).glyph(), "space": TTGlyphPen(None).glyph()}
cmap = {32: "space"}
metricas = {".notdef": (AVANCO, 0), "space": (AVANCO, 0)}


def adiciona(ch, partes):
    nome = "uni%04X" % ord(ch)
    glifos[nome] = desenha(partes)
    metricas[nome] = (AVANCO, 0)
    cmap[ord(ch)] = nome
    if len(ch.lower()) == 1 and ch.lower() != ch:
        cmap[ord(ch.lower())] = nome


for ch, linhas in G.items():
    adiciona(ch, [(linhas, 0)])
for ch, (base, ac) in COM_ACENTO.items():
    adiciona(ch, [(ACENTOS[ac], -2), (G[base], 0)])
adiciona("Ç", [(G["C"], 0), (["..#..", ".#..."], 7)])   # Ç

ordem = list(glifos.keys())
