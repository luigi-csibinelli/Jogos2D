fb.setupGlyphOrder(ordem)
fb.setupCharacterMap(cmap)
fb.setupGlyf(glifos)
fb.setupHorizontalMetrics(metricas)
fb.setupHorizontalHeader(ascent=1000, descent=-300)
fb.setupNameTable({"familyName": "PixelDHS", "styleName": "Regular"})
fb.setupOS2(sTypoAscender=1000, sTypoDescender=-300, usWinAscent=1000, usWinDescent=300)
fb.setupPost()
fb.save(os.path.join(SAIDA, "PixelDHS.ttf"))
